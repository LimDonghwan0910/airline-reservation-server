    template_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aircraft_id          VARCHAR(10) NOT NULL,
    departure_airport_id VARCHAR(10) NOT NULL,
    arrival_airport_id   VARCHAR(10) NOT NULL,
    start_date           DATE NOT NULL,
    end_date             DATE NOT NULL,
    departure_time       TIME NOT NULL,
    arrival_time         TIME NOT NULL,
    price                INTEGER NOT NULL,
    is_monday            BOOLEAN DEFAULT FALSE NOT NULL,
    is_tuesday           BOOLEAN DEFAULT FALSE NOT NULL,
    is_wednesday         BOOLEAN DEFAULT FALSE NOT NULL,
    is_thursday          BOOLEAN DEFAULT FALSE NOT NULL,
    is_friday            BOOLEAN DEFAULT FALSE NOT NULL,
    is_saturday          BOOLEAN DEFAULT FALSE NOT NULL,
    is_sunday            BOOLEAN DEFAULT FALSE NOT NULL,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
