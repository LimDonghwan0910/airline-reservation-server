-- DB初期化
DROP TABLE IF EXISTS passenger_details CASCADE;
DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS schedule_seats CASCADE;
DROP TABLE IF EXISTS schedules CASCADE;
DROP TABLE IF EXISTS schedule_templates CASCADE;
DROP TABLE IF EXISTS airports CASCADE;
DROP TABLE IF EXISTS aircrafts CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS user_roles CASCADE;

-- ユーザー種別
CREATE TABLE user_roles (
    role_code INT PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE user_roles IS 'ユーザー種別';
COMMENT ON COLUMN user_roles.role_code IS '権限コード';
COMMENT ON COLUMN user_roles.role_name IS '権限名';
COMMENT ON COLUMN user_roles.created_by IS '初回登録ユーザーID';
COMMENT ON COLUMN user_roles.created_at IS '初回登録日時';
COMMENT ON COLUMN user_roles.updated_by IS '最終更新ユーザーID';
COMMENT ON COLUMN user_roles.updated_at IS '最終更新日時';

-- ユーザーテーブル
CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code INT NOT NULL,
    user_name VARCHAR(50) NOT NULL,
    birth_date DATE NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone_number VARCHAR(20) NOT NULL,
    password VARCHAR(255) NOT NULL,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (role_code) REFERENCES user_roles(role_code)
);

COMMENT ON TABLE users IS 'ユーザー';
COMMENT ON COLUMN users.user_id IS 'ユーザーID';
COMMENT ON COLUMN users.role_code IS '権限コード';
COMMENT ON COLUMN users.user_name IS '会員名';
COMMENT ON COLUMN users.birth_date IS '生年月日';
COMMENT ON COLUMN users.email IS 'メールアドレス';
COMMENT ON COLUMN users.phone_number IS '携帯電話番号';
COMMENT ON COLUMN users.password IS 'パスワード';
COMMENT ON COLUMN users.is_deleted IS '退会フラグ';
COMMENT ON COLUMN users.created_by IS '初回登録ユーザーID';
COMMENT ON COLUMN users.created_at IS '初回登録日時';
COMMENT ON COLUMN users.updated_by IS '最終更新ユーザーID';
COMMENT ON COLUMN users.updated_at IS '最終更新日時';


