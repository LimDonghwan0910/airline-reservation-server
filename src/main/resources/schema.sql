COMMENT ON COLUMN schedule_templates.end_date IS '定期運航終了日';
COMMENT ON COLUMN schedule_templates.departure_time IS '出発時刻';
COMMENT ON COLUMN schedule_templates.arrival_time IS '到着時刻';
COMMENT ON COLUMN schedule_templates.price IS '料金';
