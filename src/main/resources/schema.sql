-- 運航スケジュール
CREATE TABLE schedules (
    schedule_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id          INT,
    aircraft_id          VARCHAR(10) NOT NULL,
    departure_airport_id VARCHAR(10) NOT NULL,
    arrival_airport_id   VARCHAR(10) NOT NULL,
    departure_datetime   TIMESTAMP NOT NULL,
    arrival_datetime     TIMESTAMP NOT NULL,
    status               VARCHAR(20) DEFAULT 'SCHEDULED' NOT NULL,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (template_id) REFERENCES schedule_templates(template_id) ON DELETE SET NULL,
    FOREIGN KEY (aircraft_id) REFERENCES aircrafts(aircraft_id),
    FOREIGN KEY (departure_airport_id) REFERENCES airports(airport_id),
    FOREIGN KEY (arrival_airport_id) REFERENCES airports(airport_id)
);

COMMENT ON TABLE schedules IS '実日付別運航スケジュール';
COMMENT ON COLUMN schedules.schedule_id IS 'スケジュールID (PK)';
COMMENT ON COLUMN schedules.template_id IS '紐づくテンプレートID (FK)';
COMMENT ON COLUMN schedules.aircraft_id IS '航空機ID (FK)';
COMMENT ON COLUMN schedules.departure_airport_id IS '出発空港ID (FK)';
COMMENT ON COLUMN schedules.arrival_airport_id IS '到着空港ID (FK)';
COMMENT ON COLUMN schedules.departure_datetime IS '実際の出発日時（日付+時刻）';
COMMENT ON COLUMN schedules.arrival_datetime IS '実際の到着日時（日付+時刻）';
COMMENT ON COLUMN schedules.status IS '運航ステータス (SCHEDULED, DELAYED, CANCELLED)';

-- 便別座席状態
CREATE TABLE schedule_seats (
    scheduled_seat_no INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id INT NOT NULL,
    seat_name VARCHAR(10) NOT NULL,
    status VARCHAR(20) DEFAULT 'AVAILABLE',
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (schedule_id) REFERENCES schedules(schedule_id),
    CONSTRAINT uq_schedule_seat UNIQUE (schedule_id, seat_name)
);

COMMENT ON TABLE schedule_seats IS '便別座席状態';
COMMENT ON COLUMN schedule_seats.scheduled_seat_no IS '便別座席状態NO';
COMMENT ON COLUMN schedule_seats.schedule_id IS '運航スケジュール固有ID';
COMMENT ON COLUMN schedule_seats.seat_name IS '座席番号';
COMMENT ON COLUMN schedule_seats.status IS '座席予約ステータス';
COMMENT ON COLUMN schedule_seats.created_by IS '初回登録ユーザーID';
COMMENT ON COLUMN schedule_seats.created_at IS '初回登録日時';
COMMENT ON COLUMN schedule_seats.updated_by IS '最終更新ユーザーID';
COMMENT ON COLUMN schedule_seats.updated_at IS '最終更新日時';


-- 予約
CREATE TABLE bookings (
    booking_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    schedule_id INT NOT NULL,
    total_price INT NOT NULL,
    booking_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) DEFAULT 'COMPLETED',
    is_deleted BOOLEAN DEFAULT FALSE,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id),
    FOREIGN KEY (schedule_id) REFERENCES schedules(schedule_id)
);

