CREATE TABLE IF NOT EXISTS schedule_seats (
    scheduled_seat_no INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id INT NOT NULL,
    seat_name VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_by INT,
    created_at TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP,
    CONSTRAINT uq_test_schedule_seat UNIQUE (schedule_id, seat_name)
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    schedule_id INT NOT NULL,
    total_price INT NOT NULL,
    booking_time TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    is_deleted BOOLEAN NOT NULL,
    created_by INT,
    created_at TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS passenger_details (
    passenger_detail_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INT NOT NULL,
    passenger_name VARCHAR(50) NOT NULL,
    schedule_seat_no INT NOT NULL,
    is_deleted BOOLEAN NOT NULL,
    created_by INT,
    created_at TIMESTAMP,
    updated_by INT,
    updated_at TIMESTAMP
);
